// Generates src/design/tokens.css from src/design/tokens.json, the single source shared with the Paper design system.
// Each colour becomes one CSS variable that resolves through light-dark(), so the page follows `color-scheme`
// (set from data-color-scheme) before any JavaScript runs.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const src = resolve(here, '../src/design/tokens.json')
const out = resolve(here, '../src/design/tokens.css')
const t = JSON.parse(readFileSync(src, 'utf8'))

const { light, dark } = t.color
const missing = Object.keys(light).filter((k) => !(k in dark)).concat(Object.keys(dark).filter((k) => !(k in light)))
if (missing.length) throw new Error(`tokens.json: light and dark must define the same colours; unmatched: ${missing.join(', ')}`)

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())
const lines = Object.keys(light).map((k) => `  --${kebab(k)}: light-dark(${light[k]}, ${dark[k]});`)
lines.push(...Object.entries(t.radius).map(([k, v]) => `  --r-${k}: ${v}px;`))

const css = `/* Generated by scripts/tokens.mjs from tokens.json. Do not edit by hand. */
:root,
[data-color-scheme] {
${lines.join('\n')}
}
`
writeFileSync(out, css)
console.log(`tokens.css: ${Object.keys(light).length} colours, ${Object.keys(t.radius).length} radii`)
